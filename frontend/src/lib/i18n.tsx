const dictionaries: Record<Language, Record<MessageKey, string>> = { en: english, hi: hindi };
type LanguageContextValue = { language: Language; setLanguage: (next: Language) => void; t: (key: MessageKey) => string };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ initialLanguage, children }: { initialLanguage: Language; children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);
  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    document.cookie = `mp_language=${next}; Path=/; Max-Age=31536000; SameSite=Lax${location.protocol === "https:" ? "; Secure" : ""}`;
    document.documentElement.lang = next;
  }, []);
  const value = useMemo(
    () => ({ language, setLanguage, t: (key: MessageKey) => dictionaries[language][key] }),
    [language, setLanguage],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className="language-switcher">
      <span>{t("language")}</span>
      <select aria-label={t("language")} value={language} onChange={(event) => setLanguage(event.target.value as Language)}>
        <option value="en">{t("english")}</option>
        <option value="hi">{t("hindi")}</option>
      </select>
    </label>
  );
}
